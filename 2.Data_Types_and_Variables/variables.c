/* Variable деген не?
Variable (айнымалы) — программада ақпаратты сақтайтын орын.
Мысалы:
int age = 48;
Мұнда:
int → мәліметтің типі
age → айнымалының аты
48 → айнымалының мәні
= → мән беру операторы
*/

/*Айнымалыны қалай жариялаймыз?
Жалпы формасы:
data_type variable_name = value;
Мысалы:
int age = 48;
float salary = 500000.5;
char grade = 'A';
*/
